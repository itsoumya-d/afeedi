  /// Returns the translation for [key] in the locale currently in effect for
  /// [context].  Falls back to English if the locale is not supported, and
  /// returns [key] itself if no translation at all is found.
  static String tr(BuildContext context, String key) {
    final languageCode = Localizations.localeOf(context).languageCode;
    return _translations[key]?[languageCode] ??
        _translations[key]?['en'] ??
        key;
  }

  /// Convenience overload that accepts an explicit [locale] instead of
  /// reading it from [BuildContext].  Useful in tests and service-layer code.
  static String trLocale(Locale locale, String key) {
    return _translations[key]?[locale.languageCode] ??
        _translations[key]?['en'] ??
        key;
  }
}

/// Convenience extension so callers can write `context.tr('key')` instead of
/// `AppLocalizationsManual.tr(context, 'key')`.
extension AppLocalizationsManualExtension on BuildContext {
  String tr(String key) => AppLocalizationsManual.tr(this, key);
}
